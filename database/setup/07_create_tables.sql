SET DEFINE OFF;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

-- 1. Issuing agencies
CREATE TABLE ISSUING_AGENCY (
    AGENCY_CODE   NUMBER(5)       NOT NULL,
    AGENCY_NAME   VARCHAR2(150)   NOT NULL,
    AGENCY_SHORT  VARCHAR2(20)    NOT NULL,
    CONSTRAINT PK_ISSUING_AGENCY PRIMARY KEY (AGENCY_CODE)
        USING INDEX TABLESPACE PARK_IDX,
    CONSTRAINT UQ_AGENCY_SHORT UNIQUE (AGENCY_SHORT)
        USING INDEX TABLESPACE PARK_IDX
) TABLESPACE PARK_DATA;

-- 2. Source violation categories: P, V, T and M
CREATE TABLE VIOLATION_TYPE (
    VIOLATION_TYPE_DESC  VARCHAR2(1) NOT NULL,
    CONSTRAINT PK_VIOLATION_TYPE PRIMARY KEY (VIOLATION_TYPE_DESC)
        USING INDEX TABLESPACE PARK_IDX,
    CONSTRAINT CK_VIOLATION_TYPE_CODE
        CHECK (VIOLATION_TYPE_DESC IN ('P', 'V', 'T', 'M'))
) TABLESPACE PARK_DATA;

-- 3. Violation codes and their optional procedural descriptions
CREATE TABLE VIOLATION (
    VIOLATION_CODE      VARCHAR2(10)  NOT NULL,
    VIOLATION_PROC_DESC VARCHAR2(500),
    CONSTRAINT PK_VIOLATION PRIMARY KEY (VIOLATION_CODE)
        USING INDEX TABLESPACE PARK_IDX
) TABLESPACE PARK_DATA;

-- 4. Ticket disposition reference data
CREATE TABLE DISPOSITION (
    DISPOSITION_CODE  NUMBER(5)      NOT NULL,
    DISPOSITION_TYPE  VARCHAR2(30)   NOT NULL,
    DISPOSITION_DESC  VARCHAR2(500),
    CONSTRAINT PK_DISPOSITION PRIMARY KEY (DISPOSITION_CODE)
        USING INDEX TABLESPACE PARK_IDX
) TABLESPACE PARK_DATA;

-- 5. Distinct source location strings and optional geocoding data
-- LOCATION_ID is generated because the source has no location key.
CREATE TABLE LOCATION (
    LOCATION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    LOCATION_TEXT  VARCHAR2(300) NOT NULL,
    MAR_ID         NUMBER(12),
    XCOORD         NUMBER(15,3),
    YCOORD         NUMBER(15,3),
    LATITUDE       NUMBER(10,7),
    LONGITUDE      NUMBER(11,7),
    CONSTRAINT PK_LOCATION PRIMARY KEY (LOCATION_ID)
        USING INDEX TABLESPACE PARK_IDX,
    CONSTRAINT UQ_LOCATION_TEXT UNIQUE (LOCATION_TEXT)
        USING INDEX TABLESPACE PARK_IDX,
    CONSTRAINT CK_LOCATION_LATITUDE
        CHECK (LATITUDE IS NULL OR LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_LOCATION_LONGITUDE
        CHECK (LONGITUDE IS NULL OR LONGITUDE BETWEEN -180 AND 180)
) TABLESPACE PARK_DATA;

-- 6. Main ticket table. Each ticket references one agency, category,
-- violation code and disposition. Location is optional in the source.
CREATE TABLE PARKING_TICKET (
    TICKET_NUMBER        NUMBER(12) NOT NULL,
    SOURCE_OBJECT_ID    NUMBER(12) NOT NULL,
    VIOLATION_TYPE_DESC VARCHAR2(1) NOT NULL,
    ISSUE_DATE           TIMESTAMP WITH TIME ZONE NOT NULL,
    ISSUE_TIME           NUMBER(4) NOT NULL,
    AGENCY_CODE          NUMBER(5) NOT NULL,
    VIOLATION_CODE       VARCHAR2(10) NOT NULL,
    LOCATION_ID          NUMBER(12),
    PLATE_STATE          VARCHAR2(10),
    VEHICLE_TYPE         VARCHAR2(50),
    MULTI_OWNER_NUMBER   VARCHAR2(30) NOT NULL,
    DISPOSITION_CODE     NUMBER(5) NOT NULL,
    DISPOSITION_DATE     TIMESTAMP WITH TIME ZONE,
    FINE_AMOUNT          NUMBER(10,2) NOT NULL,
    TOTAL_PAID           NUMBER(10,2) NOT NULL,
    GIS_LAST_MOD_DTTM    TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT PK_PARKING_TICKET PRIMARY KEY (TICKET_NUMBER)
        USING INDEX TABLESPACE PARK_IDX,
    CONSTRAINT UQ_TICKET_SOURCE_OBJECT UNIQUE (SOURCE_OBJECT_ID)
        USING INDEX TABLESPACE PARK_IDX,
    CONSTRAINT FK_TICKET_VIOLATION_TYPE
        FOREIGN KEY (VIOLATION_TYPE_DESC)
        REFERENCES VIOLATION_TYPE (VIOLATION_TYPE_DESC),
    CONSTRAINT FK_TICKET_AGENCY
        FOREIGN KEY (AGENCY_CODE)
        REFERENCES ISSUING_AGENCY (AGENCY_CODE),
    CONSTRAINT FK_TICKET_VIOLATION
        FOREIGN KEY (VIOLATION_CODE)
        REFERENCES VIOLATION (VIOLATION_CODE),
    CONSTRAINT FK_TICKET_LOCATION
        FOREIGN KEY (LOCATION_ID)
        REFERENCES LOCATION (LOCATION_ID),
    CONSTRAINT FK_TICKET_DISPOSITION
        FOREIGN KEY (DISPOSITION_CODE)
        REFERENCES DISPOSITION (DISPOSITION_CODE),
    CONSTRAINT CK_TICKET_ISSUE_TIME
        CHECK (ISSUE_TIME BETWEEN 0 AND 2359),
    CONSTRAINT CK_TICKET_FINE_AMOUNT
        CHECK (FINE_AMOUNT >= 0),
    CONSTRAINT CK_TICKET_TOTAL_PAID
        CHECK (TOTAL_PAID >= 0)
) TABLESPACE PARK_DATA;

-- 7. Repeating penalty stages are normalized into child rows.
-- Each ticket can have stages 1 through 5, including source zero values.
CREATE TABLE TICKET_PENALTY (
    TICKET_NUMBER   NUMBER(12)  NOT NULL,
    PENALTY_STAGE   NUMBER(1)   NOT NULL,
    PENALTY_AMOUNT  NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_TICKET_PENALTY
        PRIMARY KEY (TICKET_NUMBER, PENALTY_STAGE)
        USING INDEX TABLESPACE PARK_IDX,
    CONSTRAINT FK_PENALTY_TICKET
        FOREIGN KEY (TICKET_NUMBER)
        REFERENCES PARKING_TICKET (TICKET_NUMBER),
    CONSTRAINT CK_PENALTY_STAGE
        CHECK (PENALTY_STAGE BETWEEN 1 AND 5),
    CONSTRAINT CK_PENALTY_AMOUNT
        CHECK (PENALTY_AMOUNT >= 0)
) TABLESPACE PARK_DATA;

-- Index foreign-key columns to support joins and parent-key maintenance.
CREATE INDEX IX_TICKET_AGENCY
    ON PARKING_TICKET (AGENCY_CODE) TABLESPACE PARK_IDX;
CREATE INDEX IX_TICKET_TYPE
    ON PARKING_TICKET (VIOLATION_TYPE_DESC) TABLESPACE PARK_IDX;
CREATE INDEX IX_TICKET_VIOLATION
    ON PARKING_TICKET (VIOLATION_CODE) TABLESPACE PARK_IDX;
CREATE INDEX IX_TICKET_LOCATION
    ON PARKING_TICKET (LOCATION_ID) TABLESPACE PARK_IDX;
CREATE INDEX IX_TICKET_DISPOSITION
    ON PARKING_TICKET (DISPOSITION_CODE) TABLESPACE PARK_IDX;

-- Table descriptions for the database dictionary.
COMMENT ON TABLE ISSUING_AGENCY IS
    'Reference list of agencies that issued the source parking citations.';
COMMENT ON TABLE VIOLATION_TYPE IS
    'Source ticket category codes: P, V, T and M.';
COMMENT ON TABLE VIOLATION IS
    'Reference list of parking violation codes and optional descriptions.';
COMMENT ON TABLE DISPOSITION IS
    'Reference list of source ticket disposition codes and descriptions.';
COMMENT ON TABLE LOCATION IS
    'Distinct source location strings with optional address and coordinate data.';
COMMENT ON TABLE PARKING_TICKET IS
    'One row per parking citation in the September 2026 source dataset.';
COMMENT ON TABLE TICKET_PENALTY IS
    'One row per ticket and penalty stage; preserves all five source stages.';

-- Final verification: expected result is seven rows.
SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
    'ISSUING_AGENCY',
    'VIOLATION_TYPE',
    'VIOLATION',
    'DISPOSITION',
    'LOCATION',
    'PARKING_TICKET',
    'TICKET_PENALTY'
)
ORDER BY TABLE_NAME;

