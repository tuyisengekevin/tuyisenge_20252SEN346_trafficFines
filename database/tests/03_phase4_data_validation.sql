-- Phase IV validation queries. Run after staging import and final data load.
-- These are evidence queries: record the actual output/screenshots.
-- Expected staging row count from the dataset card: 89,078.

PROMPT 1. Raw staging row count (expected 89078)
SELECT COUNT(*) AS STAGING_ROWS FROM PARKING_TICKET_STAGE;

PROMPT 2. Duplicate source object IDs in staging (expected 0)
SELECT OBJECTID, COUNT(*) AS ROW_COUNT
FROM PARKING_TICKET_STAGE
GROUP BY OBJECTID
HAVING COUNT(*) > 1;

PROMPT 3. Duplicate ticket numbers in staging (expected 0)
SELECT TICKET_NUMBER, COUNT(*) AS ROW_COUNT
FROM PARKING_TICKET_STAGE
GROUP BY TICKET_NUMBER
HAVING COUNT(*) > 1;

PROMPT 4. Invalid ticket category values (expected no rows)
SELECT VIOLATION_TYPE_DESC, COUNT(*) AS ROW_COUNT
FROM PARKING_TICKET_STAGE
WHERE TRIM(VIOLATION_TYPE_DESC) NOT IN ('P', 'V', 'T', 'M')
GROUP BY VIOLATION_TYPE_DESC;

PROMPT 5. Invalid or negative fine values (expected no rows)
SELECT FINE_AMOUNT
FROM PARKING_TICKET_STAGE
WHERE VALIDATE_CONVERSION(TRIM(FINE_AMOUNT) AS NUMBER) = 0
   OR TO_NUMBER(TRIM(FINE_AMOUNT)) < 0;

PROMPT 6. Final normalized row counts
SELECT 'PARKING_TICKET' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM PARKING_TICKET
UNION ALL
SELECT 'TICKET_PENALTY', COUNT(*) FROM TICKET_PENALTY
UNION ALL
SELECT 'LOCATION', COUNT(*) FROM LOCATION
UNION ALL
SELECT 'ISSUING_AGENCY', COUNT(*) FROM ISSUING_AGENCY
UNION ALL
SELECT 'VIOLATION', COUNT(*) FROM VIOLATION
UNION ALL
SELECT 'DISPOSITION', COUNT(*) FROM DISPOSITION;

PROMPT 7. Orphan ticket foreign keys (expected all zero)
SELECT
    (SELECT COUNT(*) FROM PARKING_TICKET t
      WHERE NOT EXISTS (SELECT 1 FROM ISSUING_AGENCY a
                        WHERE a.AGENCY_CODE = t.AGENCY_CODE)) AS ORPHAN_AGENCY,
    (SELECT COUNT(*) FROM PARKING_TICKET t
      WHERE NOT EXISTS (SELECT 1 FROM VIOLATION v
                        WHERE v.VIOLATION_CODE = t.VIOLATION_CODE)) AS ORPHAN_VIOLATION,
    (SELECT COUNT(*) FROM PARKING_TICKET t
      WHERE NOT EXISTS (SELECT 1 FROM DISPOSITION d
                        WHERE d.DISPOSITION_CODE = t.DISPOSITION_CODE)) AS ORPHAN_DISPOSITION
FROM DUAL;

PROMPT 8. Constraint state (expected ENABLED and VALIDATED)
SELECT CONSTRAINT_NAME, TABLE_NAME, STATUS, VALIDATED
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN ('ISSUING_AGENCY', 'VIOLATION_TYPE', 'VIOLATION',
                     'DISPOSITION', 'LOCATION', 'PARKING_TICKET',
                     'TICKET_PENALTY')
ORDER BY TABLE_NAME, CONSTRAINT_NAME;
