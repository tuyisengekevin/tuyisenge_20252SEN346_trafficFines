-- Phase IV reporting views. Run as KEVIN_ADMIN in the project PDB.
-- If a view already exists, review it before replacing it with CREATE OR REPLACE.

CREATE OR REPLACE VIEW V_TICKET_REPORT AS
SELECT
    t.TICKET_NUMBER,
    t.ISSUE_DATE,
    t.ISSUE_TIME,
    a.AGENCY_NAME,
    a.AGENCY_SHORT,
    t.VIOLATION_TYPE_DESC,
    t.VIOLATION_CODE,
    v.VIOLATION_PROC_DESC,
    l.LOCATION_TEXT,
    t.PLATE_STATE,
    t.FINE_AMOUNT,
    t.TOTAL_PAID,
    d.DISPOSITION_TYPE,
    d.DISPOSITION_DESC
FROM PARKING_TICKET t
JOIN ISSUING_AGENCY a ON a.AGENCY_CODE = t.AGENCY_CODE
JOIN VIOLATION v ON v.VIOLATION_CODE = t.VIOLATION_CODE
JOIN DISPOSITION d ON d.DISPOSITION_CODE = t.DISPOSITION_CODE
LEFT JOIN LOCATION l ON l.LOCATION_ID = t.LOCATION_ID;

CREATE OR REPLACE VIEW V_AGENCY_TICKET_SUMMARY AS
SELECT
    a.AGENCY_CODE,
    a.AGENCY_NAME,
    COUNT(t.TICKET_NUMBER) AS TICKET_COUNT,
    SUM(t.FINE_AMOUNT) AS TOTAL_FINE_AMOUNT,
    SUM(t.TOTAL_PAID) AS TOTAL_REPORTED_PAID
FROM ISSUING_AGENCY a
LEFT JOIN PARKING_TICKET t ON t.AGENCY_CODE = a.AGENCY_CODE
GROUP BY a.AGENCY_CODE, a.AGENCY_NAME;

-- Check-option view: inserts/updates through this view must continue to
-- satisfy the positive-fine filter. This is not a read-only view.
CREATE OR REPLACE VIEW V_POSITIVE_FINE_TICKETS AS
SELECT TICKET_NUMBER, ISSUE_DATE, AGENCY_CODE, VIOLATION_CODE,
       FINE_AMOUNT, TOTAL_PAID
FROM PARKING_TICKET
WHERE FINE_AMOUNT > 0
WITH CHECK OPTION CONSTRAINT CK_V_POSITIVE_FINE;

-- Verify that all three views are valid.
SELECT OBJECT_NAME, STATUS
FROM USER_OBJECTS
WHERE OBJECT_TYPE = 'VIEW'
  AND OBJECT_NAME IN ('V_TICKET_REPORT',
                      'V_AGENCY_TICKET_SUMMARY',
                      'V_POSITIVE_FINE_TICKETS')
ORDER BY OBJECT_NAME;
