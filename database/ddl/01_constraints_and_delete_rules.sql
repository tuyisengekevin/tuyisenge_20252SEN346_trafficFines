-- Project: Parking Violations Analytics and Fine Management System
-- Schema: KEVIN_ADMIN
-- PDB: I_20252SEN346_KEVIN_PARK_DB
-- Purpose: Apply and validate the Phase IV referential-action design.
--
-- IMPORTANT:
-- 1. Connect as KEVIN_ADMIN to the project PDB.
-- 2. This script assumes the seven existing tables were created by
--    database/setup/07_create_tables.sql. DO NOT recreate tables.
-- 3. Oracle DDL commits implicitly. Review the two FK changes before run.
-- 4. If child rows exist, the constraints must be revalidated against them.
-- ============================================================

SET DEFINE OFF;
WHENEVER SQLERROR EXIT SQL.SQLCODE;

PROMPT Replacing location FK with ON DELETE SET NULL...
ALTER TABLE PARKING_TICKET
    DROP CONSTRAINT FK_TICKET_LOCATION;

ALTER TABLE PARKING_TICKET
    ADD CONSTRAINT FK_TICKET_LOCATION
    FOREIGN KEY (LOCATION_ID)
    REFERENCES LOCATION (LOCATION_ID)
    ON DELETE SET NULL
    ENABLE VALIDATE;

PROMPT Replacing penalty FK with ON DELETE CASCADE...
ALTER TABLE TICKET_PENALTY
    DROP CONSTRAINT FK_PENALTY_TICKET;

ALTER TABLE TICKET_PENALTY
    ADD CONSTRAINT FK_PENALTY_TICKET
    FOREIGN KEY (TICKET_NUMBER)
    REFERENCES PARKING_TICKET (TICKET_NUMBER)
    ON DELETE CASCADE
    ENABLE VALIDATE;

PROMPT Enabling and validating existing named constraints...
ALTER TABLE ISSUING_AGENCY
    MODIFY CONSTRAINT PK_ISSUING_AGENCY ENABLE VALIDATE;
ALTER TABLE ISSUING_AGENCY
    MODIFY CONSTRAINT UQ_AGENCY_SHORT ENABLE VALIDATE;

ALTER TABLE VIOLATION_TYPE
    MODIFY CONSTRAINT PK_VIOLATION_TYPE ENABLE VALIDATE;
ALTER TABLE VIOLATION_TYPE
    MODIFY CONSTRAINT CK_VIOLATION_TYPE_CODE ENABLE VALIDATE;

ALTER TABLE VIOLATION
    MODIFY CONSTRAINT PK_VIOLATION ENABLE VALIDATE;

ALTER TABLE DISPOSITION
    MODIFY CONSTRAINT PK_DISPOSITION ENABLE VALIDATE;

ALTER TABLE LOCATION
    MODIFY CONSTRAINT PK_LOCATION ENABLE VALIDATE;
ALTER TABLE LOCATION
    MODIFY CONSTRAINT UQ_LOCATION_TEXT ENABLE VALIDATE;
ALTER TABLE LOCATION
    MODIFY CONSTRAINT CK_LOCATION_LATITUDE ENABLE VALIDATE;
ALTER TABLE LOCATION
    MODIFY CONSTRAINT CK_LOCATION_LONGITUDE ENABLE VALIDATE;

ALTER TABLE PARKING_TICKET
    MODIFY CONSTRAINT PK_PARKING_TICKET ENABLE VALIDATE;
ALTER TABLE PARKING_TICKET
    MODIFY CONSTRAINT UQ_TICKET_SOURCE_OBJECT ENABLE VALIDATE;
ALTER TABLE PARKING_TICKET
    MODIFY CONSTRAINT FK_TICKET_VIOLATION_TYPE ENABLE VALIDATE;
ALTER TABLE PARKING_TICKET
    MODIFY CONSTRAINT FK_TICKET_AGENCY ENABLE VALIDATE;
ALTER TABLE PARKING_TICKET
    MODIFY CONSTRAINT FK_TICKET_VIOLATION ENABLE VALIDATE;
ALTER TABLE PARKING_TICKET
    MODIFY CONSTRAINT FK_TICKET_DISPOSITION ENABLE VALIDATE;
ALTER TABLE PARKING_TICKET
    MODIFY CONSTRAINT CK_TICKET_ISSUE_TIME ENABLE VALIDATE;
ALTER TABLE PARKING_TICKET
    MODIFY CONSTRAINT CK_TICKET_FINE_AMOUNT ENABLE VALIDATE;
ALTER TABLE PARKING_TICKET
    MODIFY CONSTRAINT CK_TICKET_TOTAL_PAID ENABLE VALIDATE;

ALTER TABLE TICKET_PENALTY
    MODIFY CONSTRAINT PK_TICKET_PENALTY ENABLE VALIDATE;
ALTER TABLE TICKET_PENALTY
    MODIFY CONSTRAINT CK_PENALTY_STAGE ENABLE VALIDATE;
ALTER TABLE TICKET_PENALTY
    MODIFY CONSTRAINT CK_PENALTY_AMOUNT ENABLE VALIDATE;

PROMPT Constraint status report (all should be ENABLED and VALIDATED)...
SELECT CONSTRAINT_NAME, TABLE_NAME, CONSTRAINT_TYPE,
       STATUS, VALIDATED, DELETE_RULE
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN (
    'ISSUING_AGENCY', 'VIOLATION_TYPE', 'VIOLATION',
    'DISPOSITION', 'LOCATION', 'PARKING_TICKET', 'TICKET_PENALTY'
)
ORDER BY TABLE_NAME, CONSTRAINT_TYPE, CONSTRAINT_NAME;

PROMPT Referential-action report...
SELECT CONSTRAINT_NAME, TABLE_NAME, DELETE_RULE, STATUS, VALIDATED
FROM USER_CONSTRAINTS
WHERE CONSTRAINT_NAME IN ('FK_TICKET_LOCATION', 'FK_PENALTY_TICKET')
ORDER BY CONSTRAINT_NAME;

PROMPT Constraints script completed. Review query output before proceeding.
